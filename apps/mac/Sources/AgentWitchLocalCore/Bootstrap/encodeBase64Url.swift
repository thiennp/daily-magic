import Foundation

/// Base64url without padding (RFC 7636 / RFC 4648 §5).
public func encodeBase64Url(_ data: Data) -> String {
    data.base64EncodedString()
        .replacingOccurrences(of: "+", with: "-")
        .replacingOccurrences(of: "/", with: "_")
        .replacingOccurrences(of: "=", with: "")
}
